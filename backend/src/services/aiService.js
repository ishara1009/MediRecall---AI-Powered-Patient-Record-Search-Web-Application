const axios = require('axios');
const fs = require('fs');
const FormData = require('form-data');
const logger = require('../utils/logger');

const AI_SERVICE_URL = process.env.AI_SERVICE_URL || 'http://localhost:8000';

class AIService {
  /**
   * Check the health of AI microservice.
   */
  async healthCheck() {
    try {
      const response = await axios.get(`${AI_SERVICE_URL}/health`);
      return response.data;
    } catch (error) {
      logger.error('AI Service health check failed', error.message);
      throw new Error(`AI Service is unreachable: ${error.message}`);
    }
  }

  /**
   * Upload a PDF file to the AI microservice for processing and ingestion.
   * @param {string} filePath Local path to the file on express server
   * @param {string} originalName Original name of the PDF file
   * @param {string} customId Unique document ID generated by backend
   */
  async uploadDocument(filePath, originalName, customId) {
    try {
      const form = new FormData();
      form.append('file', fs.createReadStream(filePath), {
        filename: originalName,
        contentType: 'application/pdf',
      });
      form.append('document_id', customId);

      const response = await axios.post(`${AI_SERVICE_URL}/upload`, form, {
        headers: {
          ...form.getHeaders(),
        },
        maxContentLength: Infinity,
        maxBodyLength: Infinity,
      });

      return response.data;
    } catch (error) {
      logger.error(`AI Service upload failed for file ${originalName}`, error.message);
      throw new Error(`AI Service failed to process PDF: ${error.response?.data?.detail || error.message}`);
    }
  }

  /**
   * Query the RAG QA chain.
   * @param {string} question Question query
   */
  async queryChat(question, documentId) {
    try {
      const response = await axios.post(`${AI_SERVICE_URL}/chat`, { question, document_id: documentId });
      return response.data;
    } catch (error) {
      logger.error(`AI Service chat query failed`, error.message);
      throw new Error(`AI Service QA search failed: ${error.response?.data?.detail || error.message}`);
    }
  }

  /**
   * Request deletion of a document from the AI Service Vector Store.
   * @param {string} customId Unique document ID
   */
  async deleteDocument(customId) {
    try {
      const response = await axios.delete(`${AI_SERVICE_URL}/documents/${customId}`);
      return response.data;
    } catch (error) {
      logger.error(`AI Service delete document ${customId} failed`, error.message);
      throw new Error(`AI Service failed to delete document: ${error.response?.data?.detail || error.message}`);
    }
  }

  /**
   * Request embedding rebuild for a single document.
   * @param {string} customId Unique document ID
   */
  async rebuildDocument(customId) {
    try {
      const response = await axios.post(`${AI_SERVICE_URL}/documents/${customId}/rebuild`);
      return response.data;
    } catch (error) {
      logger.error(`AI Service rebuild document ${customId} failed`, error.message);
      throw new Error(`AI Service failed to rebuild document: ${error.response?.data?.detail || error.message}`);
    }
  }

  /**
   * Request embedding rebuild for all uploaded documents.
   */
  async rebuildAllDocuments() {
    try {
      const response = await axios.post(`${AI_SERVICE_URL}/documents/rebuild-all`);
      return response.data;
    } catch (error) {
      logger.error(`AI Service rebuild all documents failed`, error.message);
      throw new Error(`AI Service failed to rebuild all documents: ${error.response?.data?.detail || error.message}`);
    }
  }
}

module.exports = new AIService();
